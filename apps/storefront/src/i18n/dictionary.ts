export function normalizeStorefrontLocale(value?: string | null): StorefrontLocale {
  return value?.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

export function translate(locale: StorefrontLocale, key: DictionaryKey, values?: Record<string, string | number>) {
  let copy: string = dictionary[locale][key] ?? dictionary.en[key];
  if (!values) return copy;
  for (const [name, value] of Object.entries(values)) {
    copy = copy.replaceAll(`{${name}}`, String(value));
  }
  return copy;
}
